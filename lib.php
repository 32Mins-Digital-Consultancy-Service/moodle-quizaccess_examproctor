/**
 * Serve proctoring images to users who may view the proctoring report.
 *
 * @param stdClass $course
 * @param stdClass $cm
 * @param context $context
 * @param string $filearea
 * @param array $args
 * @param bool $forcedownload
 * @param array $options
 * @return bool false if the file was not found; otherwise sends the file and exits.
 */
function quizaccess_examproctor_pluginfile($course, $cm, $context, $filearea, $args, $forcedownload, array $options = []) {
    if ($context->contextlevel != CONTEXT_MODULE || $filearea !== 'snapshots') {
        return false;
    }

    require_login($course, false, $cm);
    require_capability('quizaccess/examproctor:viewreport', $context);

    $itemid = (int) array_shift($args);
    $filename = array_pop($args);
    $filepath = $args ? '/' . implode('/', $args) . '/' : '/';

    $file = get_file_storage()->get_file($context->id, 'quizaccess_examproctor', $filearea, $itemid, $filepath, $filename);
    if (!$file || $file->is_directory()) {
        return false;
    }

    // Personal data: never cache in shared caches.
    send_stored_file($file, 0, 0, $forcedownload, $options + ['cacheability' => 'private']);
}
